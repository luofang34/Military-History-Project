"""Writes the evidence ledger into the mission README, between its marker comments, so the
README's conflicts always show what build/evidence.py holds."""
from evidence import DISPUTES

START = "<!-- evidence ledger: generated by build/chastise.py from build/evidence.py -->"
END = "<!-- end of evidence ledger -->"


def cell(text):
    return text.replace("|", "\\|")


def table(names):
    rows = ["| Dispute | Records (source: what it says) | Replay estimate and basis |",
            "| --- | --- | --- |"]
    for key, d in DISPUTES.items():
        records = "<br>".join(
            f"{names[r.source]}: {r.text()}"
            for r in d.records)
        rows.append(f"| {cell(d.title)} (`{key}`) | {cell(records)} | "
                    f"**{cell(d.estimate)}**. {cell(d.basis)} |")
    return "\n".join(rows)


def write_readme(path, names):
    text = path.read_text()
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    path.write_text(f"{head}{START}\n{table(names)}\n{END}{tail}")
